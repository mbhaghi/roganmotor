export const getProduct = (slug: string) => PRODUCTS.find((p) => p.slug === slug);
export const getProductsByCategory = (cat: string) => PRODUCTS.filter((p) => p.category === cat);

/** قیمت پایهٔ نمایشی = ارزان‌ترین بستهٔ رایج */
export const fromPrice = (p: Product) => Math.min(...p.volumes.map((v) => v.price));

/**
 * محصولات مکمل برای ساخت «باندل سرویس کامل».
 * این تابع همان چیزی است که AOV را بالا می‌برد (docs/03 بخش ۳٫۲).
 */
export function serviceBundleFor(engineOilSlug: string): Product[] {
  const picks = ['coolant-oat', 'brake-fluid-dot4'];
  if (engineOilSlug.startsWith('mineral') || engineOilSlug.includes('high-mileage')) {
    picks.unshift('flushing-oil');
  }
  return picks.map((s) => PRODUCTS.find((p) => p.slug === s)).filter((p): p is Product => !!p);
}

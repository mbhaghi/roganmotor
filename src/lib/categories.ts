/** همهٔ دسته‌هایی که دست‌کم یک محصول فعال دارند */
export function activeCategories() {
  return CATEGORIES.filter((c) => getProductsByCategory(c.slug).length > 0).map((c) => {
    const list = getProductsByCategory(c.slug);
    return {
      slug: c.slug,
      name: c.name,
      icon: c.icon,
      blurb: c.blurb,
      count: list.length,
      fromPrice: Math.min(...list.map((p) => Math.min(...p.volumes.map((v) => v.price)))),
    };
  });
}

